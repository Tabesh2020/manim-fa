"""
manim_fa.animation
===================

``fa_write``: نوشتنِ متنِ فارسی از راست به چپ، با همان افکتِ اصیلِ
«دست‌نویسی» (خط‌دورِ حرف کشیده می‌شود، بعد پر می‌شود) که خودِ ``Write()``
مانیم برای متنِ انگلیسی دارد.

این تابع فقط یک لایه‌ی نازک روی ``Write(mobject, reverse=True)`` خودِ
مانیم است (که داخلش از همان ``DrawBorderThenFill`` استفاده می‌کند، یعنی
افکتِ واقعیِ نوشتن، نه صرفاً پدیدارشدنِ تکه‌تکه‌ی حروف). تنها کاری که
اضافه می‌کند: پیش‌فرض را برای فارسی به «راست‌به‌چپ» تنظیم می‌کند (چون
پیش‌فرضِ خودِ مانیم برای ``reverse`` مقدارِ False است) و برای این‌که متن
پس از نوشته‌شدن پاک نشود، ``remover=False`` را پیش‌فرض می‌کند (چون
پیش‌فرضِ خودِ مانیم وقتی ``reverse=True`` باشد این است که مانیم آن را
remover در نظر بگیرد).

نکته: ``FaText`` پیش از این، هر جعبه‌ی هایلایت را با حروفِ خودش در یک
بلوکِ واحد ادغام کرده (نگاه کنید به ``text._merge_highlight_runs``)، پس
برعکس‌کردنِ ترتیب توسط ``Write(reverse=True)`` هیچ‌وقت جعبه را از متنش
جدا نمی‌اندازد.
"""

from __future__ import annotations

from manim import Write


class _ShallowReverseWrite(Write):
    """درست مثلِ ``Write(reverse=True)`` خودِ مانیم، با یک تفاوت: فقط
    ترتیبِ سطحِ بالای زیرشیء‌ها را برعکس می‌کند (نه به‌صورت بازگشتی).
    خودِ ``Write`` از ``mobject.invert(recursive=True)`` استفاده می‌کند
    که همه‌ی سطوح تودرتو را هم برعکس می‌کند — این دقیقاً همان چیزی است
    که باعث می‌شد بلوکِ ادغام‌شده‌ی هایلایت (جعبه + حروفش، که در
    ``FaText`` عمداً در یک VGroup قرار گرفته‌اند) از داخل هم برعکس شود و
    جعبه از متنِ خودش جدا بیفتد. با برعکس‌کردنِ فقط سطحِ بالا، ترتیبِ
    داخلیِ هر VGroup (بنابراین ترتیبِ جعبه‌-سپس-متن در هر هایلایت) دست‌نخورده
    می‌ماند."""

    def reverse_submobjects(self) -> None:
        self.mobject.submobjects.reverse()


def fa_write(mobject, rtl: bool | None = None, **kwargs) -> Write:
    """
    نسخه‌ی راست‌به‌چپِ ``Write()`` برای متنِ فارسی — با همان افکتِ اصیلِ
    «دست‌نویسی» (خط‌دورِ حرف کشیده می‌شود، بعد پر می‌شود)، و ایمن برای
    متنِ دارای هایلایت (جعبه همیشه با متنِ خودش با هم ظاهر می‌شود).

    پارامترها:
        mobject: خروجیِ ``FaText`` (یا هر VMobject دیگری).
        rtl: اگر مشخص نشود، از مقداری که هنگام ساخت با
            ``FaText(..., rtl=...)`` تعیین شده استفاده می‌شود (پیش‌فرض
            کلی: True).
        **kwargs: هر پارامترِ دیگرِ ``Write`` (مثل ``run_time``,
            ``rate_func``).

    مثال:
        >>> t = FaText("سلام ==دنیا==")
        >>> self.play(fa_write(t))
    """
    if rtl is None:
        rtl = getattr(mobject, "_fa_rtl", True)

    kwargs.setdefault("remover", False)
    return _ShallowReverseWrite(mobject, reverse=rtl, **kwargs)
